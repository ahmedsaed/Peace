const {
  AndroidConfig,
  withAndroidColors,
  withAndroidColorsNight,
  withAndroidStyles,
} = require('expo/config-plugins');

const { SYSTEM_PAIR, THEMES } = require('../src/constants/themes');

/**
 * Make Android's own surfaces — the date and time pickers, system alerts —
 * follow Peace's theme rather than the phone's, in Peace's colours.
 *
 * TWO PROBLEMS, ONE OF THEM SOLVED AT RUNTIME. Native dialogs are drawn by
 * Android from the ACTIVITY's theme, and Expo generates `AppTheme` with a
 * `Theme.AppCompat.DayNight` parent, which follows the phone's night mode.
 * Peace used to be dark-only and pinned the parent to plain (dark)
 * `Theme.AppCompat`. With a light theme that pin is wrong half the time, so the
 * parent stays DayNight and `ThemeRoot` forces the app's night mode to match
 * the theme with `Appearance.setColorScheme` — AppCompat then resolves
 * `values-night/` for a dark theme and `values/` for a light one.
 *
 * THE PICKER COLOURS are resources in those two folders: Ledger's in
 * `values-night`, Paper's in `values` (`SYSTEM_PAIR`). A native resource cannot
 * be swapped at runtime, so Graphite's dialogs are Ledger's and Mist's are
 * Paper's — the same lightness as the screen behind them, which is what a
 * white dialog over a black app got wrong, if not the exact shade.
 *
 * `@react-native-community/datetimepicker` builds the default (non-spinner)
 * dialog with no explicit style, so it resolves `android:datePickerDialogTheme`
 * and `android:timePickerDialogTheme` from the activity's theme — pointing
 * those two attributes at our own dialog styles is enough, with no prop to
 * pass and no fork of the library.
 *
 * Both namespaces of `colorAccent` are set on purpose: the DatePicker and
 * TimePicker widgets are framework views and read `android:colorAccent`, while
 * the dialog's own buttons come from AppCompat and read the bare `colorAccent`.
 * Setting only one leaves half the dialog blue.
 *
 * This lives in a config plugin because `android/` is regenerated by
 * `expo prebuild` — editing styles.xml directly would be undone by the next
 * native build.
 */

const COLOR_TOKENS = ['ground', 'surface', 'raised', 'ink', 'muted', 'accent'];
const color = (token) => `@color/peace_${token}`;

const item = (name, value) => ({ $: { name }, _: value });

/**
 * The dialog theme alone gets the buttons and the selection, but NOT the header
 * band or the clock face: those are properties of the DatePicker and TimePicker
 * *widgets*, which default to a platform grey that ignores `colorAccent`
 * entirely. Without these two widget styles the dialogs come out amber-on-grey,
 * which looks more like a half-finished theme than the untouched default did.
 */
const WIDGET_STYLES = [
  {
    name: 'PeaceDatePickerStyle',
    attr: 'android:datePickerStyle',
    parent: 'android:Widget.Material.DatePicker',
    items: [
      ['android:headerBackground', color('raised')],
      ['android:yearListSelectorColor', color('accent')],
    ],
  },
  {
    name: 'PeaceTimePickerStyle',
    attr: 'android:timePickerStyle',
    parent: 'android:Widget.Material.TimePicker',
    items: [
      ['android:headerBackground', color('raised')],
      ['android:numbersBackgroundColor', color('raised')],
      ['android:numbersTextColor', color('ink')],
      ['android:numbersSelectorColor', color('accent')],
      ['android:amPmTextColor', color('ink')],
    ],
  },
];

const DIALOG_STYLES = [
  {
    name: 'PeaceDatePickerDialog',
    attr: 'android:datePickerDialogTheme',
    widget: WIDGET_STYLES[0],
  },
  {
    name: 'PeaceTimePickerDialog',
    attr: 'android:timePickerDialogTheme',
    widget: WIDGET_STYLES[1],
  },
];

/** One theme's colours as `peace_*` colour resources. */
function withColors(plugin, theme) {
  return (config) =>
    plugin(config, (cfg) => {
      for (const token of COLOR_TOKENS) {
        cfg.modResults = AndroidConfig.Colors.assignColorValue(cfg.modResults, {
          name: `peace_${token}`,
          value: THEMES[theme].colors[token],
        });
      }
      return cfg;
    });
}

module.exports = function withNativeTheme(config) {
  config = withColors(withAndroidColors, SYSTEM_PAIR.light)(config);
  config = withColors(withAndroidColorsNight, SYSTEM_PAIR.dark)(config);
  return withAndroidStyles(config, (cfg) => {
    const styles = cfg.modResults.resources.style ?? [];

    for (const style of styles) {
      if (style.$.name !== 'AppTheme') continue;

      // DayNight, so the night mode ThemeRoot sets picks the resource folder.
      style.$.parent = 'Theme.AppCompat.DayNight.NoActionBar';
      style.item = style.item ?? [];

      // System alerts ("Replace everything?") take their buttons from the
      // activity's accent, which is AppCompat's teal unless we say otherwise.
      for (const attr of ['colorAccent', 'android:colorAccent']) {
        if (!style.item.some((i) => i.$.name === attr)) style.item.push(item(attr, color('accent')));
      }

      for (const { name, attr } of DIALOG_STYLES) {
        if (!style.item.some((i) => i.$.name === attr)) {
          style.item.push(item(attr, `@style/${name}`));
        }
      }
    }

    for (const { name, widget } of DIALOG_STYLES) {
      if (styles.some((s) => s.$.name === name)) continue;
      styles.push({
        $: { name, parent: 'Theme.AppCompat.DayNight.Dialog' },
        item: [
          // Selection ring and highlighted day/hour (framework widgets).
          item('android:colorAccent', color('accent')),
          // OK / Cancel (AppCompat buttons).
          item('colorAccent', color('accent')),
          item('android:windowBackground', color('surface')),
          item('android:textColorPrimary', color('ink')),
          item('android:textColorSecondary', color('muted')),
          item(widget.attr, `@style/${widget.name}`),
        ],
      });
    }

    for (const { name, parent, items } of WIDGET_STYLES) {
      if (styles.some((s) => s.$.name === name)) continue;
      styles.push({
        $: { name, parent },
        item: items.map(([attr, value]) => item(attr, value)),
      });
    }

    cfg.modResults.resources.style = styles;
    return cfg;
  });
};
