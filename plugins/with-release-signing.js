const { withAppBuildGradle } = require('expo/config-plugins');

/**
 * Sign release builds with our own key instead of Expo's debug keystore.
 *
 * Expo's template points the release buildType at `signingConfigs.debug`, which
 * every Expo project on earth shares. An app signed with it cannot be updated by
 * an APK signed with anything else — Android treats a different signature as a
 * different app — so the identity has to become ours before there is data worth
 * keeping.
 *
 * Credentials come from Gradle properties, never from the repository:
 *   PEACE_STORE_FILE, PEACE_STORE_PASSWORD, PEACE_KEY_ALIAS, PEACE_KEY_PASSWORD
 * set in ~/.gradle/gradle.properties locally, and injected from secrets in CI.
 *
 * FALLS BACK TO DEBUG SIGNING when those properties are absent. A fresh clone,
 * or a CI run on a fork without access to secrets, still produces a working APK
 * rather than a confusing build failure — it just is not upgrade-compatible.
 *
 * This is a config plugin because `android/` is regenerated by `expo prebuild`,
 * which would discard a direct edit to build.gradle.
 */
const SIGNING_CONFIG = `
        peaceRelease {
            if (project.hasProperty('PEACE_STORE_FILE')) {
                storeFile file(PEACE_STORE_FILE)
                storePassword PEACE_STORE_PASSWORD
                keyAlias PEACE_KEY_ALIAS
                keyPassword PEACE_KEY_PASSWORD
            }
        }`;

module.exports = function withReleaseSigning(config) {
  return withAppBuildGradle(config, (cfg) => {
    let gradle = cfg.modResults.contents;

    // Add our signing config alongside the generated `debug` one.
    if (!gradle.includes('peaceRelease {')) {
      gradle = gradle.replace(
        /(signingConfigs\s*\{)/,
        `$1${SIGNING_CONFIG}`
      );
    }

    // Point the release buildType at it, but only when the credentials exist.
    gradle = gradle.replace(
      /(buildTypes\s*\{[\s\S]*?release\s*\{[\s\S]*?)signingConfig signingConfigs\.debug/,
      `$1signingConfig project.hasProperty('PEACE_STORE_FILE') ? signingConfigs.peaceRelease : signingConfigs.debug`
    );

    cfg.modResults.contents = gradle;
    return cfg;
  });
};
