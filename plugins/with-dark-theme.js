const { withAndroidStyles } = require('expo/config-plugins');

/**
 * Force the Android app theme to dark.
 *
 * Peace is dark-only, but Expo generates `AppTheme` with a
 * `Theme.AppCompat.DayNight` parent, which follows the PHONE's dark-mode
 * setting rather than the app's. Native dialogs — the date and time pickers,
 * system alerts — inherit that theme, so on a phone in light mode they render
 * as a bright white sheet in the middle of a warm dark app.
 *
 * `app.json`'s `userInterfaceStyle: "dark"` does not fix this: it drives the JS
 * colour scheme, not the native theme parent.
 *
 * `Theme.AppCompat` (without `.Light` or `.DayNight`) is the dark variant, so
 * switching the parent pins every native surface to dark regardless of the
 * system setting.
 *
 * This lives in a config plugin because `android/` is regenerated by
 * `expo prebuild` — editing styles.xml directly would be undone by the next
 * native build.
 */
module.exports = function withDarkTheme(config) {
  return withAndroidStyles(config, (cfg) => {
    for (const style of cfg.modResults.resources.style ?? []) {
      if (style.$.name === 'AppTheme') {
        style.$.parent = 'Theme.AppCompat.NoActionBar';
      }
    }
    return cfg;
  });
};
