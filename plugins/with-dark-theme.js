const { withAndroidStyles } = require('expo/config-plugins');

const palette = require('../src/constants/palette');

/**
 * Force the Android app theme to dark, and paint the native date/time dialogs
 * with the app's own palette.
 *
 * Peace is dark-only, but Expo generates `AppTheme` with a
 * `Theme.AppCompat.DayNight` parent, which follows the PHONE's dark-mode
 * setting rather than the app's. Native dialogs — the date and time pickers,
 * system alerts — inherit that theme, so on a phone in light mode they render
 * as a bright white sheet in the middle of a warm dark app.
 *
 * `app.json`'s `userInterfaceStyle: "dark"` does not fix this: it drives the JS
 * colour scheme, not the native theme parent.
 *
 * `Theme.AppCompat` (without `.Light` or `.DayNight`) is the dark variant, so
 * switching the parent pins every native surface to dark regardless of the
 * system setting.
 *
 * THE PICKER COLOURS ARE A SEPARATE PROBLEM. Dark is not the same as themed:
 * the date and time dialogs still drew their selection ring, header and buttons
 * in the platform's default blue, which is the one thing on screen that is not
 * ours. `@react-native-community/datetimepicker` builds the default (non-spinner)
 * dialog with no explicit style, so it resolves `android:datePickerDialogTheme`
 * and `android:timePickerDialogTheme` from the ACTIVITY's theme — which means
 * pointing those two attributes at our own dialog styles is enough, with no
 * prop to pass and no fork of the library.
 *
 * Both namespaces of `colorAccent` are set on purpose: the DatePicker and
 * TimePicker widgets are framework views and read `android:colorAccent`, while
 * the dialog's own buttons come from AppCompat and read the bare `colorAccent`.
 * Setting only one leaves half the dialog blue.
 *
 * This lives in a config plugin because `android/` is regenerated by
 * `expo prebuild` — editing styles.xml directly would be undone by the next
 * native build.
 */

const item = (name, value) => ({ $: { name }, _: value });

/**
 * The dialog theme alone gets the buttons and the selection, but NOT the header
 * band or the clock face: those are properties of the DatePicker and TimePicker
 * *widgets*, which default to a platform grey that ignores `colorAccent`
 * entirely. Without these two widget styles the dialogs come out amber-on-grey,
 * which looks more like a half-finished theme than the untouched default did.
 */
const WIDGET_STYLES = [
  {
    name: 'PeaceDatePickerStyle',
    attr: 'android:datePickerStyle',
    parent: 'android:Widget.Material.DatePicker',
    items: [
      ['android:headerBackground', palette.raised],
      ['android:yearListSelectorColor', palette.accent],
    ],
  },
  {
    name: 'PeaceTimePickerStyle',
    attr: 'android:timePickerStyle',
    parent: 'android:Widget.Material.TimePicker',
    items: [
      ['android:headerBackground', palette.raised],
      ['android:numbersBackgroundColor', palette.raised],
      ['android:numbersTextColor', palette.ink],
      ['android:numbersSelectorColor', palette.accent],
      ['android:amPmTextColor', palette.ink],
    ],
  },
];

const DIALOG_STYLES = [
  {
    name: 'PeaceDatePickerDialog',
    attr: 'android:datePickerDialogTheme',
    widget: WIDGET_STYLES[0],
  },
  {
    name: 'PeaceTimePickerDialog',
    attr: 'android:timePickerDialogTheme',
    widget: WIDGET_STYLES[1],
  },
];

module.exports = function withDarkTheme(config) {
  return withAndroidStyles(config, (cfg) => {
    const styles = cfg.modResults.resources.style ?? [];

    for (const style of styles) {
      if (style.$.name !== 'AppTheme') continue;

      style.$.parent = 'Theme.AppCompat.NoActionBar';
      style.item = style.item ?? [];

      for (const { name, attr } of DIALOG_STYLES) {
        if (!style.item.some((i) => i.$.name === attr)) {
          style.item.push(item(attr, `@style/${name}`));
        }
      }
    }

    for (const { name, widget } of DIALOG_STYLES) {
      if (styles.some((s) => s.$.name === name)) continue;
      styles.push({
        $: { name, parent: 'Theme.AppCompat.Dialog' },
        item: [
          // Selection ring and highlighted day/hour (framework widgets).
          item('android:colorAccent', palette.accent),
          // OK / Cancel (AppCompat buttons).
          item('colorAccent', palette.accent),
          item('android:windowBackground', palette.surface),
          item('android:textColorPrimary', palette.ink),
          item('android:textColorSecondary', palette.muted),
          item(widget.attr, `@style/${widget.name}`),
        ],
      });
    }

    for (const { name, parent, items } of WIDGET_STYLES) {
      if (styles.some((s) => s.$.name === name)) continue;
      styles.push({
        $: { name, parent },
        item: items.map(([attr, value]) => item(attr, value)),
      });
    }

    cfg.modResults.resources.style = styles;
    return cfg;
  });
};
